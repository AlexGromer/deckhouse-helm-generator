// writeSharedInput writes sharedInput (web and api share objects) to dir/in.
func writeSharedInput(t *testing.T, dir string) string {
	t.Helper()
	in := filepath.Join(dir, "in")
	if err := os.MkdirAll(in, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(in, "app.yaml"), []byte(sharedInput), 0o644); err != nil {
		t.Fatal(err)
	}
	return in
}

// With --library-ref file://<path> the service charts depend on a library
// directory next to them: helm dependency build, helm lint --strict and helm
// template pass on every chart, and the release is complete.
func TestLibraryFileRef(t *testing.T) {
	helm := requireHelm(t)
	for _, tc := range []struct {
		name    string
		args    []string
		library string // the chart name and directory of the library
		version string
	}{
		{"default", []string{"--library-ref", "file://../library"}, "library", "0.1.0"},
		{"exact-version", []string{"--library-ref", "file://../common-lib", "--library-version", "0.3.0"}, "common-lib", "0.3.0"},
		{"range", []string{"--library-ref", "file://../library", "--library-version", ">=0.1.0 <1.0.0"}, "library", "0.1.0"},
		{"with-shared-chart", []string{"--library-ref", "file://../library", "--shared-chart", "platform"}, "library", "0.1.0"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			dir := t.TempDir()
			in := writeSharedInput(t, dir)
			out := filepath.Join(dir, "out")
			args := append([]string{"generate", "-f", in, "-o", out, "--chart-name", "app", "--mode", "library", "--include-schema"}, tc.args...)
			log := runOK(t, dhgBin, args...)
			if !strings.Contains(log, "helm dependency build") {
				t.Errorf("no hint to build the dependency:\n%s", log)
			}

			// The library is written next to the service charts, not into them.
			libYAML, err := os.ReadFile(filepath.Join(out, tc.library, "Chart.yaml"))
			if err != nil {
				t.Fatalf("library chart is not written: %v", err)
			}
			for _, want := range []string{"name: " + tc.library, "version: " + tc.version, "type: library"} {
				if !strings.Contains(string(libYAML), want) {
					t.Errorf("library Chart.yaml lacks %q:\n%s", want, libYAML)
				}
			}
			for _, svc := range []string{"web", "api"} {
				if fileExists(filepath.Join(out, svc, "charts")) {
					t.Errorf("%s: the library was vendored", svc)
				}
				chartYAML, err := os.ReadFile(filepath.Join(out, svc, "Chart.yaml"))
				if err != nil {
					t.Fatal(err)
				}
				if !strings.Contains(string(chartYAML), "repository: file://../"+tc.library) {
					t.Errorf("%s Chart.yaml:\n%s", svc, chartYAML)
				}
			}

			// checkCharts runs helm dependency build, helm lint --strict and
			// helm template on each chart.
			if _, complete := checkCharts(t, helm, out); !complete {
				t.Error("some chart was not rendered")
			}
			for _, svc := range []string{"web", "api"} {
				if !fileExists(filepath.Join(out, svc, "charts")) {
					t.Errorf("%s: helm dependency build fetched nothing", svc)
				}
			}
			checkReleaseIntegrity(t, helm, in, out, true)
		})
	}
}

// A library that exists already, at an absolute path, gives its name and
// version: the service charts depend on exactly that.
func TestLibraryFileRef_ExistingLibraryAbsolutePath(t *testing.T) {
	helm := requireHelm(t)
	dir := t.TempDir()
	in := writeSharedInput(t, dir)

	// The library, generated by an earlier run.
	first := filepath.Join(dir, "first")
	runOK(t, dhgBin, "generate", "-f", in, "-o", first, "--chart-name", "app", "--mode", "library",
		"--library-ref", "file://../org-common", "--library-version", "2.1.0")
	lib := filepath.Join(first, "org-common")

	out := filepath.Join(dir, "out")
	runOK(t, dhgBin, "generate", "-f", in, "-o", out, "--chart-name", "app", "--mode", "library",
		"--library-ref", "file://"+lib)
	chartYAML, err := os.ReadFile(filepath.Join(out, "web", "Chart.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"name: org-common", "version: 2.1.0", "repository: file://" + lib} {
		if !strings.Contains(string(chartYAML), want) {
			t.Errorf("web Chart.yaml lacks %q:\n%s", want, chartYAML)
		}
	}
	for _, svc := range []string{"web", "api"} {
		if o, err := run(helm, "dependency", "build", filepath.Join(out, svc)); err != nil {
			t.Fatalf("helm dependency build %s failed:\n%s", svc, o)
		}
		if o, err := run(helm, "lint", "--strict", filepath.Join(out, svc)); err != nil {
			t.Errorf("helm lint %s failed:\n%s", svc, o)
		}
		renderChart(t, helm, out, svc)
	}
}

func TestLibraryRefSchemes_Errors(t *testing.T) {
	dir := t.TempDir()
	in := writeSharedInput(t, dir)
	for name, tc := range map[string]struct {
		args []string
		want string
	}{
		"https needs a name":    {[]string{"--library-ref", "https://charts.example.com/stable", "--library-version", "1.0.0"}, "--library-name"},
		"https needs a version": {[]string{"--library-ref", "https://charts.example.com/stable", "--library-name", "lib"}, "--library-version"},
		"name without ref":      {[]string{"--library-name", "lib"}, "--library-ref"},
		"unknown scheme":        {[]string{"--library-ref", "ftp://example.com/lib", "--library-version", "1.0.0"}, "file://"},
		"file with a bad name":  {[]string{"--library-ref", "file://" + dir + "/in", "--library-name", "Bad_Name"}, "not a valid chart name"},
	} {
		out, err := run(dhgBin, append([]string{"generate", "-f", in, "-o", filepath.Join(dir, "o-"+strings.ReplaceAll(name, " ", "-")), "--chart-name", "app", "--mode", "library"}, tc.args...)...)
		if err == nil || !strings.Contains(out, tc.want) {
			t.Errorf("%s: err = %v, output:\n%s", name, err, out)
		}
	}
}

// https:// charts repository: the dependency is written as given, nothing is
// vendored (the repository is not reachable here, so no helm dependency build).
func TestLibraryHTTPSRepository(t *testing.T) {
	dir := t.TempDir()
	in := writeSharedInput(t, dir)
	out := filepath.Join(dir, "out")
	runOK(t, dhgBin, "generate", "-f", in, "-o", out, "--chart-name", "app", "--mode", "library",
		"--library-ref", "https://charts.example.com/stable", "--library-name", "platform-lib", "--library-version", "~1.4.0")
	chartYAML, err := os.ReadFile(filepath.Join(out, "web", "Chart.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"name: platform-lib", "version: ~1.4.0", "repository: https://charts.example.com/stable"} {
		if !strings.Contains(string(chartYAML), want) {
			t.Errorf("web Chart.yaml lacks %q:\n%s", want, chartYAML)
		}
	}
	if fileExists(filepath.Join(out, "web", "charts")) {
		t.Error("the library was vendored")
	}
}
