// inferManifests is a platform of three services (prefix "qa-") with an init
// container that reaches a database by address.
func inferManifests() string {
	var b strings.Builder
	for _, svc := range []string{"orders", "billing", "users"} {
		fmt.Fprintf(&b, `---
apiVersion: apps/v1
kind: Deployment
metadata:
  name: qa-%[1]s
  namespace: shop
  labels:
    app: %[1]s
spec:
  selector:
    matchLabels:
      app: %[1]s
  template:
    metadata:
      labels:
        app: %[1]s
        team: platform
    spec:
      initContainers:
        - name: wait-for-db
          image: registry.example.com/tools/wait:1.2
          env:
            - name: DB_HOST
              value: 10.1.2.3
      containers:
        - name: %[1]s
          image: registry.example.com/shop/%[1]s:2.0.0
          envFrom:
            - configMapRef:
                name: qa-common-config
---
apiVersion: v1
kind: Service
metadata:
  name: qa-%[1]s
  namespace: shop
spec:
  selector:
    app: %[1]s
  ports:
    - port: 80
      targetPort: 8080
`, svc)
	}
	return b.String()
}

func writeInferInput(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "platform.yaml"), []byte(inferManifests()), 0o644); err != nil {
		t.Fatal(err)
	}
	return dir
}

func TestProfileInferCmd_File(t *testing.T) {
	in := writeInferInput(t)
	out := t.TempDir()
	profilePath := filepath.Join(out, "profile.yaml")
	valuesPath := filepath.Join(out, "values-shop.yaml")
	if _, err := executeCmd(t, "profile", "infer", "-s", "file", "-f", in, "-o", profilePath, "--values-out", valuesPath); err != nil {
		t.Fatalf("profile infer: %v", err)
	}
	data, err := os.ReadFile(profilePath)
	if err != nil {
		t.Fatal(err)
	}
	text := string(data)
	if !strings.HasPrefix(text, "# Generated by dhg profile infer (source: file, min-share: 0.9)") {
		t.Errorf("header:\n%s", text)
	}
	for _, want := range []string{"prefix: qa-", "{{ .Vars.dbHost }}", "wait-for-db", "{{ .Vars.prefix }}common-config", "team: platform"} {
		if !strings.Contains(text, want) {
			t.Errorf("profile lacks %q:\n%s", want, text)
		}
	}
	if strings.Contains(text, "10.1.2.3") {
		t.Errorf("the stand's address is in the profile:\n%s", text)
	}
	values, err := os.ReadFile(valuesPath)
	if err != nil {
		t.Fatalf("values file: %v", err)
	}
	var v struct {
		Vars map[string]string `json:"vars"`
	}
	if err := yaml.Unmarshal(values, &v); err != nil || v.Vars["dbHost"] != "10.1.2.3" {
		t.Errorf("values = %s (%v)", values, err)
	}

	// Same input, same bytes.
	second := filepath.Join(out, "second.yaml")
	if _, err := executeCmd(t, "profile", "infer", "-f", in, "-s", "file", "-o", second, "--values-out", filepath.Join(out, "v2.yaml")); err != nil {
		t.Fatal(err)
	}
	again, _ := os.ReadFile(second)
	if string(again) != text {
		t.Errorf("two runs differ")
	}
}

func TestProfileInferCmd_StdoutKeepsValues(t *testing.T) {
	in := writeInferInput(t)
	out, err := executeCmd(t, "profile", "infer", "-s", "file", "-f", in)
	if err != nil {
		t.Fatalf("profile infer: %v", err)
	}
	if !strings.Contains(out, "dbHost: 10.1.2.3") {
		t.Errorf("without --values-out the stand's value stays in the profile:\n%s", out)
	}
}

func TestProfileInferCmd_NamespaceAndMinShare(t *testing.T) {
	in := writeInferInput(t)
	out := filepath.Join(t.TempDir(), "p.yaml")
	if _, err := executeCmd(t, "profile", "infer", "-s", "file", "-f", in, "-n", "shop", "--min-share", "1", "-o", out); err != nil {
		t.Fatalf("profile infer: %v", err)
	}
	if _, err := executeCmd(t, "profile", "infer", "-s", "file", "-f", in, "-n", "elsewhere", "-o", out); err == nil {
		t.Error("a namespace without Deployments: want an error")
	}
}

func TestProfileInferCmd_Errors(t *testing.T) {
	in := writeInferInput(t)
	for name, args := range map[string][]string{
		"file source needs paths": {"profile", "infer", "-s", "file"},
		"unknown source":          {"profile", "infer", "-s", "image", "-f", in},
		"min-share zero":          {"profile", "infer", "-s", "file", "-f", in, "--min-share", "0"},
		"min-share above one":     {"profile", "infer", "-s", "file", "-f", in, "--min-share", "1.5"},
	} {
		if _, err := executeCmd(t, args...); err == nil {
			t.Errorf("%s: want an error", name)
		}
	}
}
