package secretname

import "testing"

func TestSensitive(t *testing.T) {
	secret := []string{
		"DB_PASSWORD", "db_password", "SVC_PASSWD", "KEYCLOAK_CLIENT_SECRET", "AUTH_TOKEN", "TOKEN",
		"SERVICE_CREDENTIALS", "TLS_PRIVATE_KEY", "PRIVATEKEY", "STRIPE_API_KEY", "API_KEY", "APIKEY",
		"S3_ACCESS_KEY", "SPRING_DATASOURCE_PASSWORD", "DBPASSWORD", "spring.security.oauth2.client-secret",
		"HIKARI_PASSWORDS", "KC_DB_PASSWORD", "KEYCLOAK_ADMIN_PASSWORD", "APP_TOKENSERVICE_CLIENTSECRET",
		"APP_CLIENTSECRET", "GITHUB_TOKEN",
	}
	for _, name := range secret {
		if !Sensitive(name) {
			t.Errorf("%s must be sensitive", name)
		}
	}
	plain := []string{
		"KEYCLOAK_URL", "TOKEN_URL", "TOKEN_URI", "AUTH_TOKEN_HOST", "PASSWORD_PORT", "SECRET_ENDPOINT",
		"LOGGING_LEVEL", "KAFKA_HOST", "SECRETARY_NAME", "KEYSTORE_TYPE", "PRIMARY_KEY", "DB_PASSWORD_FILE",
		"TOKEN_ENABLED", "MONKEY_COUNT", "SUPPORT", "",
		"MAX_TOKENS", "OPENAI_MAX_TOKENS", "TOKEN_TTL", "TOKEN_EXPIRY", "TOKEN_EXPIRATION", "PASSWORD_MIN_LENGTH",
		"SECRET_MAX_AGE_COUNT", "PASSWORD_LIMIT", "TOKEN_TIMEOUT", "API_KEY_MAX", "PASSWORD_MIN",
		// Settings around a token are not the token.
		"ACCESS_TOKEN_VALIDITY_SECONDS", "APP_TOKENSERVICE_SERVICE", "APP_TOKEN_SERVICE", "APP_TOKENSERVICE_GRANTTYPE",
		"APP_TOKENSERVICE_CLIENTID", "APP_TOKENSERVICE_TOKEN_URL", "QOAUTH_VALIDATE_TOKENS", "USE_TOKEN_FOR_FEIGN",
		"USE_TOKEN_FOR_CLIENT", "TOKEN_VALIDITY_SECONDS", "KEYCLOAK_CLIENT_SECRET_GRANTTYPE", "DB_PASSWORD_SERVICE",
	}
	for _, name := range plain {
		if Sensitive(name) {
			t.Errorf("%s must not be sensitive", name)
		}
	}
}
